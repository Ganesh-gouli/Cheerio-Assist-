import React, { useState } from 'react';
import { 
  Headphones, 
  CheckCircle2, 
  Clock, 
  Copy, 
  Check, 
  RotateCcw, 
  AlertTriangle,
  Download
} from 'lucide-react';
import type { EscalationTicket } from '../types';
import { DEFAULT_USER } from '../data/mockData';

interface Screen6EscalationProps {
  reason: string;
  attemptedSteps: string[];
  errorCode?: string;
  userNotes?: string;
  onGoHome: () => void;
  onRestart: () => void;
}

export const Screen6Escalation: React.FC<Screen6EscalationProps> = ({
  reason,
  attemptedSteps,
  errorCode = 'Meta 133010 / OAuth Handshake Error',
  userNotes,
  onGoHome,
  onRestart
}) => {
  const [copied, setCopied] = useState(false);
  const [extraNote, setExtraNote] = useState('');
  const [noteAdded, setNoteAdded] = useState(false);

  const ticket: EscalationTicket = {
    ticketId: `CH-${Math.floor(10000 + Math.random() * 90000)}`,
    createdAt: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    issueCategory: 'WhatsApp Cloud API Onboarding',
    escalationReason: reason || 'Automated self-service diagnostic reached confidence limit',
    businessName: DEFAULT_USER.businessName,
    contactEmail: 'elena@freshbakepantry.com',
    attemptedSteps: attemptedSteps.length > 0 ? attemptedSteps : [
      'Identified WhatsApp phone number conflict',
      'Checked mobile app deregistration status',
      'Executed 6-digit SMS verification simulation'
    ],
    errorCode: errorCode,
    userNotes: userNotes,
    priority: 'High',
    estimatedResponseTime: '~18 minutes (Priority Growth Tier)',
    isSimulated: true
  };

  const handleCopySummary = () => {
    const summaryText = `[Simulated Cheerio Case #${ticket.ticketId}]
Business: ${ticket.businessName} (${ticket.contactEmail})
Category: ${ticket.issueCategory}
Reason: ${ticket.escalationReason}
Error: ${ticket.errorCode}
Attempted Steps:
${ticket.attemptedSteps.map((s, i) => `  ${i + 1}. ${s}`).join('\n')}
Priority: ${ticket.priority}`;

    navigator.clipboard.writeText(summaryText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadReport = () => {
    const summaryText = `# Simulated Cheerio Support Case Diagnostic Report
Case ID: ${ticket.ticketId}
Generated At: ${ticket.createdAt}
Business: ${ticket.businessName} (${ticket.contactEmail})
Category: ${ticket.issueCategory}
Reason for Escalation: ${ticket.escalationReason}
Error Code: ${ticket.errorCode}
Priority: ${ticket.priority}

## Diagnostic Trail & Attempted Steps:
${ticket.attemptedSteps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

${extraNote ? `## User Note:\n${extraNote}\n` : ''}
---
Note: This is a simulated diagnostic report generated by Cheerio Assist Copilot.
`;

    const blob = new Blob([summaryText], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `cheerio_case_${ticket.ticketId}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-3xl mx-auto px-4 py-8 space-y-6 animate-fadeIn">
      {/* Simulation Warning Banner (Crucial Requirement) */}
      <div className="bg-amber-50 border border-amber-200 rounded-xl p-4 flex items-start gap-3 text-amber-900 text-xs">
        <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
        <div className="space-y-1">
          <span className="font-bold uppercase tracking-wider text-[11px] text-amber-950">
            Simulated Support Escalation
          </span>
          <p className="leading-relaxed">
            This screen demonstrates the <strong>warm handover architecture</strong> for Cheerio customer support. No live support ticket has been dispatched to production servers.
          </p>
        </div>
      </div>

      {/* Main Ticket Confirmation Card */}
      <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden">
        {/* Ticket Header */}
        <div className="p-6 border-b border-slate-100 bg-slate-50/70 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-indigo-600 text-white flex items-center justify-center shadow-xs">
              <Headphones className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="text-xs font-mono font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded border border-indigo-200">
                  Case #{ticket.ticketId}
                </span>
                <span className="text-[11px] font-semibold text-rose-700 bg-rose-50 px-2 py-0.5 rounded border border-rose-200">
                  {ticket.priority} Priority
                </span>
              </div>
              <h1 className="text-lg font-bold text-slate-900 mt-1">
                Warm Support Handover Prepared
              </h1>
            </div>
          </div>

          <div className="text-right">
            <span className="text-[11px] text-slate-500 block">Typical Response SLA</span>
            <span className="text-xs font-bold text-slate-800 flex items-center justify-end gap-1">
              <Clock className="w-3.5 h-3.5 text-indigo-600" />
              {ticket.estimatedResponseTime}
            </span>
          </div>
        </div>

        {/* Ticket Details Body */}
        <div className="p-6 space-y-6 text-xs sm:text-sm">
          {/* Why We Escalated */}
          <div className="space-y-1.5">
            <h3 className="font-bold text-slate-900 text-xs uppercase tracking-wider">
              Reason for Escalation:
            </h3>
            <div className="p-3 bg-slate-50 border border-slate-200/90 rounded-xl text-slate-700 leading-relaxed">
              {ticket.escalationReason}
            </div>
          </div>

          {/* Diagnostic Context Transferred (No user repeat) */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <h3 className="font-bold text-slate-900 text-xs uppercase tracking-wider">
                Transferred Diagnostic Trace (What the Agent Sees):
              </h3>
              <span className="text-[11px] text-emerald-700 font-medium flex items-center gap-1">
                <CheckCircle2 className="w-3 h-3 text-emerald-600" />
                State Auto-Captured
              </span>
            </div>

            <div className="bg-slate-50 border border-slate-200 rounded-xl p-4 space-y-3">
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
                <div>
                  <span className="text-slate-400 block text-[11px]">Business Profile:</span>
                  <span className="font-medium text-slate-800">{ticket.businessName}</span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[11px]">Primary Contact:</span>
                  <span className="font-medium text-slate-800">{ticket.contactEmail}</span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[11px]">System Diagnostic Code:</span>
                  <span className="font-mono text-slate-800 bg-white px-2 py-0.5 rounded border border-slate-200 inline-block mt-0.5">
                    {ticket.errorCode}
                  </span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[11px]">User Technical Comfort:</span>
                  <span className="text-indigo-600 font-medium">Non-Technical Business Owner</span>
                </div>
              </div>

              <div className="pt-2 border-t border-slate-200/60">
                <span className="text-slate-500 font-semibold text-[11px] block mb-1.5">
                  Steps Already Attempted by User (Eliminates Redundant Questions):
                </span>
                <ul className="space-y-1 text-slate-600">
                  {ticket.attemptedSteps.map((step, idx) => (
                    <li key={idx} className="flex items-center gap-2">
                      <span className="w-4 h-4 rounded-full bg-slate-200 text-slate-600 flex items-center justify-center text-[10px] shrink-0">
                        {idx + 1}
                      </span>
                      <span>{step}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>
          </div>

          {/* Add Additional Note */}
          <div className="space-y-2">
            <h3 className="font-bold text-slate-900 text-xs uppercase tracking-wider">
              Add Additional Note or Screenshot Details:
            </h3>
            {!noteAdded ? (
              <div className="flex items-center gap-2">
                <input
                  type="text"
                  value={extraNote}
                  onChange={(e) => setExtraNote(e.target.value)}
                  placeholder="e.g. 'I also tried on Chrome and Safari, same error.'"
                  className="flex-1 px-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-xs text-slate-800 placeholder-slate-400 focus:outline-none focus:ring-1 focus:ring-indigo-500"
                />
                <button
                  type="button"
                  onClick={() => { if (extraNote.trim()) setNoteAdded(true); }}
                  className="px-3.5 py-2 bg-slate-800 hover:bg-slate-900 text-white text-xs font-semibold rounded-lg transition cursor-pointer"
                >
                  Append Note
                </button>
              </div>
            ) : (
              <div className="p-3 bg-emerald-50 border border-emerald-200 rounded-lg text-xs text-emerald-800 flex items-center justify-between">
                <span>Note attached to Case #{ticket.ticketId}: "{extraNote}"</span>
                <button onClick={() => setNoteAdded(false)} className="text-[11px] underline cursor-pointer">Edit</button>
              </div>
            )}
          </div>
        </div>

        {/* Ticket Footer Actions */}
        <div className="p-5 border-t border-slate-100 bg-slate-50 flex flex-col sm:flex-row items-center justify-between gap-3">
          <div className="flex flex-wrap items-center gap-2 w-full sm:w-auto">
            <button
              onClick={handleCopySummary}
              className="px-4 py-2.5 bg-white hover:bg-slate-100 border border-slate-200 text-slate-700 rounded-xl text-xs font-semibold shadow-2xs transition flex items-center justify-center gap-1.5 cursor-pointer"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-slate-500" />}
              <span>{copied ? 'Summary Copied!' : 'Copy Context'}</span>
            </button>

            <button
              onClick={handleDownloadReport}
              className="px-4 py-2.5 bg-white hover:bg-indigo-50 border border-slate-200 text-indigo-700 hover:border-indigo-300 rounded-xl text-xs font-semibold shadow-2xs transition flex items-center justify-center gap-1.5 cursor-pointer"
              title="Download diagnostic state report as markdown"
            >
              <Download className="w-3.5 h-3.5 text-indigo-600" />
              <span>Export Report (.md)</span>
            </button>
          </div>

          <div className="flex items-center gap-2 w-full sm:w-auto">
            <button
              onClick={onGoHome}
              className="w-full sm:w-auto px-4 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-semibold shadow-xs transition cursor-pointer text-center"
            >
              Back to Support Home
            </button>
            <button
              onClick={onRestart}
              className="w-full sm:w-auto px-3.5 py-2.5 bg-white hover:bg-slate-100 border border-slate-200 text-slate-700 rounded-xl text-xs font-medium transition cursor-pointer flex items-center justify-center gap-1"
              title="Restart journey"
            >
              <RotateCcw className="w-3.5 h-3.5 text-slate-500" />
              <span className="sm:hidden">Reset</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
